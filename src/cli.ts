async function readStdin(): Promise<string> {
  const chunks: Buffer[] = [];
  for await (const chunk of process.stdin) {
    chunks.push(chunk);
  }
  return Buffer.concat(chunks).toString('utf-8');
}

async function pathExists(path: string): Promise<boolean> {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
}

async function writeOptimizePrompt(projectRoot: string): Promise<void> {
  const promptPath = join(projectRoot, '.context', 'optimize.md');
  await writeFile(promptPath, OPTIMIZE_PROMPT, 'utf-8');
}

async function detectEnvironment(projectRoot: string): Promise<Environment> {
  const claudeExists = await pathExists(join(projectRoot, '.claude'));
  const geminiExists = await pathExists(join(projectRoot, '.gemini'));

  if (claudeExists && geminiExists) {
    const claudeSettings = await pathExists(join(projectRoot, '.claude', 'settings.json'));
    const geminiSettings = await pathExists(join(projectRoot, '.gemini', 'settings.json'));
    if (claudeSettings && !geminiSettings) return 'claude';
    if (geminiSettings && !claudeSettings) return 'gemini';
    return 'claude';
  }

  if (claudeExists) return 'claude';
  if (geminiExists) return 'gemini';

  if (process.env.CLAUDE_CODE || process.env.ANTHROPIC_API_KEY) return 'claude';
  if (process.env.GEMINI_API_KEY || process.env.GOOGLE_API_KEY) return 'gemini';

  return 'claude';
}

async function installHook(projectRoot: string, forceEnv?: Environment): Promise<void> {
  const env = forceEnv || await detectEnvironment(projectRoot);

  if (env === 'unknown') {
    console.log('Could not detect AI CLI environment.');
    console.log('Use --claude or --gemini flag to specify.');
    return;
  }

  const config = ENVIRONMENTS[env];
  const settingsDir = join(projectRoot, config.settingsDir);
  const settingsPath = join(settingsDir, config.settingsFile);

  await mkdir(settingsDir, { recursive: true });

  let settings: Record<string, unknown> = {};
  try {
    const content = await readFile(settingsPath, 'utf-8');
    settings = JSON.parse(content);
  } catch {
    // File doesn't exist
  }

  if (!settings.hooks) settings.hooks = {};
  const hooks = settings.hooks as Record<string, unknown[]>;
  if (!hooks[config.hookEvent]) hooks[config.hookEvent] = [];

  const eventHooks = hooks[config.hookEvent] as Array<Record<string, unknown>>;
  const hasHook = eventHooks.some((h) => {
    const hHooks = h.hooks as Array<Record<string, unknown>> | undefined;
    return hHooks?.some((hh) => String(hh.command || '').includes('ctx-pilot'));
  });

  if (hasHook) {
    console.log(`Hook already installed for ${config.name}.`);
    return;
  }

  eventHooks.push({
    matcher: '',
    hooks: [{ type: 'command', command: 'npx ctx-pilot' }],
  });

  await writeFile(settingsPath, JSON.stringify(settings, null, 2) + '\n', 'utf-8');
  console.log(`Hook installed for ${config.name} at ${config.settingsDir}/${config.settingsFile}`);
}

