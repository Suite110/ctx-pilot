function parseEnvFlag(args: string[]): Environment | undefined {
  if (args.includes('--claude')) return 'claude';
  if (args.includes('--gemini')) return 'gemini';
  return undefined;
}

function parseExportTargets(args: string[]): ExportTarget[] {
  const targets: ExportTarget[] = [];
  if (args.includes('--cursor')) targets.push('cursor');
  if (args.includes('--windsurf')) targets.push('windsurf');
  if (args.includes('--aider')) targets.push('aider');
  if (args.includes('--mdc')) targets.push('mdc');
  if (args.includes('--all')) {
    return ['cursor', 'windsurf', 'aider', 'mdc'];
  }
  return targets;
}

async function main(): Promise<void> {
  const args = process.argv.slice(2);
  const projectRoot = process.cwd();
  const forceEnv = parseEnvFlag(args);
  const exportTargets = parseExportTargets(args);

  switch (args[0]) {
    case 'init':
      await runInit(projectRoot, forceEnv);
      break;
    case 'status':
      await runStatus(projectRoot);
      break;
    case 'auto-index':
    case 'index':
      await runAutoIndex(projectRoot, {
        verbose: args.includes('--verbose') || args.includes('-v'),
        force: args.includes('--force') || args.includes('-f'),
      });
      break;
    case 'validate':
      await runValidate(projectRoot);
      break;
    case 'search': {
      const searchQuery = args.slice(1).join(' ');
      if (!searchQuery) {
        console.error('Usage: ctx-pilot search <query>');
        process.exit(1);
      }
      await runSearch(projectRoot, searchQuery);
      break;
    }
    case 'watch':
      await runWatch(projectRoot);
      break;
    case 'hook':
    case 'install':
    case 'install-hook':
      await installHook(projectRoot, forceEnv);
      break;
    case 'export':
      if (exportTargets.length === 0) {
        console.error('Specify export target: --cursor, --windsurf, --aider, --mdc, or --all');
        process.exit(1);
      }
      for (const target of exportTargets) {
        await runExport(projectRoot, target);
      }
      break;
    case 'help':
    case '--help':
    case '-h':
      printHelp();
      break;
    default:
      await runHook();
  }
}

main().catch((error) => {
  console.error('Error:', error.message);
  process.exit(1);
});
